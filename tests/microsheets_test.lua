test("every function has help, and its examples hold", function()
  local fnhelp = require "fnhelp"
  for _, name in ipairs(formula.names()) do
    ok(fnhelp.doc(name), name .. " has no help")
  end
  local known = {}
  for _, name in ipairs(formula.names()) do known[name] = true end
  local b, s = sheet(fnhelp.sample)
  local bad = {}
  for _, f in ipairs(fnhelp.functions) do
    ok(known[f.name], f.name .. " is documented but not a function")
    if not f.alias then
      ok(f.does and f.params and f.examples and #f.examples > 0, f.name .. " is missing parts")
      ok(fnhelp.page(f.name), f.name .. " has no page")
      for _, ex in ipairs(f.examples) do
        b:set(s, 1, 5, ex[1])
        local got = b:display(s, 1, 5)
        if got ~= ex[2] then bad[#bad + 1] = ("%s gives %s, not %s"):format(ex[1], got, ex[2]) end
      end
    end
  end
  ok(#bad == 0, "\n       " .. table.concat(bad, "\n       "))
  eq(fnhelp.syntax(fnhelp.doc("SUMIF")), "SUMIF(range, criterion, [sum_range])")
  eq(fnhelp.syntax(fnhelp.doc("SUM"), 2), "SUM(number1, [NUMBER2], ...)")
  eq(fnhelp.doc("avg").aliasOf, "AVERAGE")
  eq(fnhelp.param(fnhelp.doc("SUM"), 5)[1], "number2")
end)

