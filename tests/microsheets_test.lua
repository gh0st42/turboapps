-- sheet makes a workbook from rows of what was typed, and returns it and
-- its first sheet.
local function sheet(rows)
  local b = book.new()
  local s = b.sheets[1]
  for r, row in ipairs(rows) do
    for c, raw in pairs(row) do s:put(r, c, raw) end
  end
  b:recalc()
  return b, s
end

-- calc works out one formula over rows, as cell Z100.
local function calc(text, rows)
  local b, s = sheet(rows or {})
  b:set(s, 100, 26, text)
  return b:display(s, 100, 26)
end

